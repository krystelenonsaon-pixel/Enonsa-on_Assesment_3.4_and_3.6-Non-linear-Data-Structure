"""
Assessment 3.4: Non-Linear Data Structure
Binary Search Tree built from the unique letters of the last name "Enonsaon".
"""

class Node:
    def __init__(self, value):
        self.value = value
        self.left = None
        self.right = None


class BinaryTree:
    def __init__(self):
        self.root = None

    def insert(self, value):
        if self.root is None:
            self.root = Node(value)
        else:
            self._insert_recursive(self.root, value)

    def _insert_recursive(self, current, value):
        if value < current.value:
            if current.left is None:
                current.left = Node(value)
            else:
                self._insert_recursive(current.left, value)
        else:
            if current.right is None:
                current.right = Node(value)
            else:
                self._insert_recursive(current.right, value)

    # Breadth-First Search (level-order traversal)
    def bfs(self):
        if self.root is None:
            return []

        result = []
        queue = [self.root]

        while queue:
            current = queue.pop(0)
            result.append(current.value)

            if current.left is not None:
                queue.append(current.left)
            if current.right is not None:
                queue.append(current.right)

        return result

    # Depth-First Search traversals
    def dfs_preorder(self):
        result = []
        self._preorder(self.root, result)
        return result

    def _preorder(self, node, result):
        if node is not None:
            result.append(node.value)
            self._preorder(node.left, result)
            self._preorder(node.right, result)

    def dfs_inorder(self):
        result = []
        self._inorder(self.root, result)
        return result

    def _inorder(self, node, result):
        if node is not None:
            self._inorder(node.left, result)
            result.append(node.value)
            self._inorder(node.right, result)

    def dfs_postorder(self):
        result = []
        self._postorder(self.root, result)
        return result

    def _postorder(self, node, result):
        if node is not None:
            self._postorder(node.left, result)
            self._postorder(node.right, result)
            result.append(node.value)


if __name__ == "__main__":
    last_name_letters = ["E", "N", "O", "S", "A"]

    tree = BinaryTree()
    for letter in last_name_letters:
        tree.insert(letter)

    print("Letters inserted:", last_name_letters)
    print("BFS (level-order):", tree.bfs())
    print("DFS Pre-order:    ", tree.dfs_preorder())
    print("DFS In-order:     ", tree.dfs_inorder())
    print("DFS Post-order:   ", tree.dfs_postorder())
